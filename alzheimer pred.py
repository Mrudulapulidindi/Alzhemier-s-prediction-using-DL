import opendatasets as od
od.download("https://www.kaggle.com/datasets/lukechugh/best-alzheimer-mri-dataset-99-accuracy?utm_source=chatgpt.com")

import os
import tensorflow as tf
from tensorflow import keras
from tensorflow.keras import layers
import matplotlib.pyplot as plt
import pickle
import numpy as np
from sklearn.metrics import confusion_matrix, classification_report
import seaborn as sns

dataset_dir = "/content/best-alzheimer-mri-dataset-99-accuracy/Combined Dataset"
train_dir = os.path.join(dataset_dir, "train")
test_dir = os.path.join(dataset_dir, "test")

print("Train path exists:", os.path.exists(train_dir))
print("Test path exists:", os.path.exists(test_dir))

img_size = (128, 128)
batch_size = 32

class_names = ['Mild Impairment', 'Moderate Impairment', 'No Impairment', 'Very Mild Impairment']

train_ds = tf.keras.utils.image_dataset_from_directory(
    train_dir,
    image_size=(128,128),
    batch_size=32,
    labels='inferred',
    label_mode='int',
    class_names=class_names,
    shuffle=True
)

test_ds = tf.keras.utils.image_dataset_from_directory(
    test_dir,
    image_size=(128,128),
    batch_size=32,
    labels='inferred',
    label_mode='int',
    class_names=class_names,
    shuffle=False
)

print("\nClasses found:", train_ds.class_names)

AUTOTUNE = tf.data.AUTOTUNE
train_ds = train_ds.cache().shuffle(1000).prefetch(buffer_size=AUTOTUNE)
test_ds = test_ds.cache().prefetch(buffer_size=AUTOTUNE)

model = keras.Sequential([
    layers.Rescaling(1./255, input_shape=(128, 128, 3)),

    layers.Conv2D(32, (3,3), activation='relu'),
    layers.MaxPooling2D(),

    layers.Conv2D(64, (3,3), activation='relu'),
    layers.MaxPooling2D(),

    layers.Conv2D(128, (3,3), activation='relu'),
    layers.MaxPooling2D(),

    layers.Flatten(),
    layers.Dense(128, activation='relu'),
    layers.Dropout(0.3),
    layers.Dense(4, activation='softmax')
])

model.compile(optimizer='adam',
              loss='sparse_categorical_crossentropy',
              metrics=['accuracy'])

model.summary()

epochs = 10
history = model.fit(train_ds, validation_data=test_ds, epochs=epochs)

model.save("/content/alzheimer_model_no_aug.h5")
with open("/content/training_history_no_aug.pkl", "wb") as f:
    pickle.dump(history.history, f)

print("Model and training history saved successfully!")

plt.figure(figsize=(12,5))

# Accuracy
plt.subplot(1,2,1)
plt.plot(history.history['accuracy'], label='Train Accuracy')
plt.plot(history.history['val_accuracy'], label='Validation Accuracy')
plt.legend()
plt.title('Model Accuracy')

# Loss
plt.subplot(1,2,2)
plt.plot(history.history['loss'], label='Train Loss')
plt.plot(history.history['val_loss'], label='Validation Loss')
plt.legend()
plt.title('Model Loss')

plt.show()

test_loss, test_acc = model.evaluate(test_ds)
print(f"\n📊 Test Accuracy: {test_acc*100:.2f}%")

y_true = np.concatenate([y for x, y in test_ds], axis=0)
y_pred = np.argmax(model.predict(test_ds), axis=1)

cm = confusion_matrix(y_true, y_pred)
plt.figure(figsize=(6,6))
sns.heatmap(cm, annot=True, fmt='d', cmap='Purples',
            xticklabels=class_names,  # Use stored class_names
            yticklabels=class_names)
plt.title("Confusion Matrix")
plt.xlabel("Predicted Label")
plt.ylabel("True Label")
plt.show()

print("\nClassification Report:\n")
print(classification_report(y_true, y_pred, target_names=class_names))